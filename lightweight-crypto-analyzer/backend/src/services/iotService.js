/**
 * Software simulation of IoT sensor readings. No physical devices are involved.
 * Each simulated device performs a bounded random walk so consecutive readings look
 * realistic. State is kept in memory for a limited number of device IDs.
 */
import { randomInt } from 'node:crypto';
import { ValidationError } from '../utils/errors.js';

const MAX_TRACKED_DEVICES = 100;
const devices = new Map();

export const SENSOR_FIELDS = Object.freeze({
  temperature: { label: 'Temperature', unit: '°C', min: 10, max: 45, step: 0.8, decimals: 1 },
  humidity: { label: 'Humidity', unit: '%RH', min: 20, max: 95, step: 3, decimals: 0 },
  soilMoisture: { label: 'Soil moisture', unit: '%', min: 5, max: 80, step: 2, decimals: 0 },
  airQuality: { label: 'Air quality index', unit: 'AQI', min: 10, max: 300, step: 6, decimals: 0 },
});

function randomBetween(min, max, decimals) {
  const scale = 10 ** decimals;
  return randomInt(Math.round(min * scale), Math.round(max * scale) + 1) / scale;
}

function step(value, field) {
  const scale = 10 ** field.decimals;
  const delta = (randomInt(-1000, 1001) / 1000) * field.step;
  const next = Math.min(field.max, Math.max(field.min, value + delta));
  return Math.round(next * scale) / scale;
}

function initialState() {
  return {
    sequence: 0,
    temperature: randomBetween(24, 34, 1),
    humidity: randomBetween(45, 75, 0),
    soilMoisture: randomBetween(25, 55, 0),
    airQuality: randomBetween(40, 110, 0),
  };
}

export function validateDeviceId(deviceId) {
  const id = deviceId ?? 'SENSOR-001';
  if (typeof id !== 'string' || !/^[A-Za-z0-9_-]{1,32}$/.test(id)) {
    throw new ValidationError('deviceId must be 1-32 characters: letters, digits, "-" or "_".', { field: 'deviceId' });
  }
  return id;
}

/** Serialises a reading in the two message formats the simulation page offers. */
export function serializeReading(reading) {
  const json = JSON.stringify({
    deviceId: reading.deviceId,
    seq: reading.sequence,
    ts: reading.timestamp,
    temperature: reading.temperature,
    humidity: reading.humidity,
    soilMoisture: reading.soilMoisture,
    airQuality: reading.airQuality,
  });
  const compact = [
    reading.deviceId,
    reading.sequence,
    Math.floor(Date.parse(reading.timestamp) / 1000),
    reading.temperature,
    reading.humidity,
    reading.soilMoisture,
    reading.airQuality,
  ].join(';');
  return { json, compact };
}

export function generateReading(deviceIdInput) {
  const deviceId = validateDeviceId(deviceIdInput);
  let state = devices.get(deviceId);
  if (!state) {
    if (devices.size >= MAX_TRACKED_DEVICES) devices.delete(devices.keys().next().value);
    state = initialState();
  } else {
    state = {
      sequence: state.sequence,
      temperature: step(state.temperature, SENSOR_FIELDS.temperature),
      humidity: step(state.humidity, SENSOR_FIELDS.humidity),
      soilMoisture: step(state.soilMoisture, SENSOR_FIELDS.soilMoisture),
      airQuality: step(state.airQuality, SENSOR_FIELDS.airQuality),
    };
  }
  state.sequence += 1;
  devices.set(deviceId, state);

  const reading = {
    deviceId,
    sequence: state.sequence,
    timestamp: new Date().toISOString(),
    temperature: state.temperature,
    humidity: state.humidity,
    soilMoisture: state.soilMoisture,
    airQuality: state.airQuality,
  };
  const messages = serializeReading(reading);
  return {
    success: true,
    simulated: true,
    reading,
    fields: SENSOR_FIELDS,
    messages,
    messageBytes: {
      json: Buffer.byteLength(messages.json, 'utf8'),
      compact: Buffer.byteLength(messages.compact, 'utf8'),
    },
    formats: {
      json: 'Compact JSON object: {"deviceId","seq","ts","temperature","humidity","soilMoisture","airQuality"}',
      compact: 'Semicolon-separated: deviceId;seq;unixTime;temperature;humidity;soilMoisture;airQuality',
    },
    note: 'Software simulation: readings are generated by the server; no physical sensors are connected.',
  };
}
